from __future__ import annotations

import json
import re
import time
import uuid
from typing import Any, Callable, Mapping, Sequence

from app.models.citation import Citation
from app.models.research import (
    STATUS_COMPLETED,
    STATUS_FAILED,
    ResearchBrief,
    ResearchContradiction,
    ResearchFinding,
    ResearchRun,
)
from app.ports.llm import LLMProvider
from app.ports.research_repository import ResearchRepository
from app.ports.vectorstore import VectorStore
from app.ports.web_search import WebSearchPort
from app.services.errors import ResearchNotFoundError, ResearchParseError
from app.services.retrieval_providers import RetrievalContext

QUESTION_PATTERNS = (
    "Definition and boundaries of {topic}",
    "Key elements of {topic}",
    "Common pitfalls of {topic}",
    "Typical application scenarios for {topic}",
    "Implementation steps for {topic}",
    "Evaluation metrics for {topic}",
    "Common issues and troubleshooting for {topic}",
    "Advanced points for {topic}",
    "Alternatives and trade-offs for {topic}",
)

PLACEHOLDER_WARNING = "No LLM key configured; this research is a placeholder synthesis based on retrieved evidence"
NO_EVIDENCE_WARNING = "No hits in the knowledge base or web search; this research was generated by an LLM from its own knowledge and has not been verified against evidence"
WEB_DISABLED_WARNING = "Web search is disabled; only knowledge-base evidence is used"
MAX_SECTION_CHARS = 400
ProgressCallback = Callable[[str, float], None]


class ResearchService:
    def __init__(
        self,
        repository: ResearchRepository,
        vectorstore: VectorStore,
        llm: LLMProvider,
        web_search: WebSearchPort | None = None,
        default_top_k: int = 6,
        max_evidence: int = 0,
        top_k_ceiling: int = 0,
        web_limit: int = 3,
        evidence_char_limit: int = MAX_SECTION_CHARS,
        min_score: float = 0.15,
        reranker_factory: Callable[[str], Any] | None = None,
        rerank_weight: float = 0.5,
        rerank_top_n: int = 0,
    ) -> None:
        self.repository = repository
        self.vectorstore = vectorstore
        self.llm = llm
        self.web_search = web_search
        self.default_top_k = default_top_k
        self.max_evidence = max(0, int(max_evidence or 0))
        self.top_k_ceiling = max(0, int(top_k_ceiling or 0))
        self.web_limit = web_limit
        self.evidence_char_limit = evidence_char_limit
        self.min_score = max(0.05, float(min_score) * 0.5)
        self.reranker_factory = reranker_factory
        self.rerank_weight = min(1.0, max(0.0, float(rerank_weight)))
        self.rerank_top_n = max(0, int(rerank_top_n or 0))

    async def run(
        self,
        topic: str,
        depth: int = 2,
        top_k: int | None = None,
        source_ids: Sequence[str] | None = None,
        tenant_id: str = "",
        user_id: str = "",
        llm: LLMProvider | None = None,
        retrieval: RetrievalContext | None = None,
        on_progress: ProgressCallback | None = None,
    ) -> ResearchRun:
        def notify(stage: str, value: float) -> None:
            if on_progress is None:
                return
            try:
                on_progress(stage, max(0.0, min(float(value), 1.0)))
            except Exception:
                pass

        resolved_topic = (topic or "").strip()
        if not resolved_topic:
            raise ValueError("research topic must not be empty")
        resolved_depth = max(1, min(int(depth or 1), 3))
        resolved_top_k = max(1, int(top_k or self.default_top_k))
        if self.top_k_ceiling > 0:
            resolved_top_k = min(resolved_top_k, self.top_k_ceiling)
        provider = llm or self.llm
        run = ResearchRun(
            id=f"research_{uuid.uuid4().hex[:16]}",
            tenant_id=tenant_id or "",
            user_id=user_id or "",
            topic=resolved_topic,
            depth=resolved_depth,
            status=STATUS_COMPLETED,
            created_at=time.time(),
            updated_at=time.time(),
            provider=type(provider).__name__,
        )
        try:
            notify("planning", 0.05)
            questions = await self._plan(provider, resolved_topic, resolved_depth)
            run.questions = questions
            notify("planning", 0.10)
            citations, web_used, web_available = await self._gather(
                questions,
                resolved_top_k,
                source_ids,
                tenant_id,
                retrieval,
                on_progress=notify,
            )
            citations = await self._apply_rerank(
                resolved_topic, citations, user_id, retrieval, on_progress=notify
            )
            run.citations = citations
            run.web_used = web_used
            notify("synthesizing", 0.65)
            brief, warning = await self._synthesize(
                provider, resolved_topic, questions, citations, resolved_depth
            )
            notify("synthesizing", 0.92)
            run.brief = brief
            run.warning = self._warning(provider, citations, web_available, warning)
            if retrieval is not None:
                run.retrieval = retrieval.summary()
                run.warnings = list(retrieval.warnings)
            notify("done", 0.95)
        except ResearchParseError:
            run.status = STATUS_FAILED
            run.warning = "research synthesis failed: the model output could not be parsed as structured JSON"
            raise
        finally:
            run.updated_at = time.time()
            self.repository.save(run)
        return run

    def get(self, run_id: str, tenant_id: str | None = None) -> ResearchRun | None:
        return self.repository.get(run_id, tenant_id)

    def list(self, tenant_id: str | None = None, limit: int = 50) -> list[ResearchRun]:
        return self.repository.list(tenant_id, limit)

    def delete(self, run_id: str, tenant_id: str | None = None) -> bool:
        return self.repository.delete(run_id, tenant_id)

    def rename(self, run_id: str, topic: str, tenant_id: str | None = None) -> ResearchRun:
        run = self.get(run_id, tenant_id)
        if run is None:
            raise ResearchNotFoundError(f"research not found: {run_id}")
        label = (topic or "").strip()
        if not label:
            raise ValueError("topic must not be empty")
        run.topic = label
        run.updated_at = time.time()
        return self.repository.save(run)

    async def _plan(
        self, provider: LLMProvider, topic: str, depth: int
    ) -> list[str]:
        count = max(1, depth) * 3
        if getattr(provider, "is_placeholder", False):
            return self._template_questions(topic, count)
        prompt = self._plan_prompt(topic, count)
        try:
            text = await provider.complete(prompt)
        except Exception:
            return self._template_questions(topic, count)
        questions = _parse_questions(text)
        if not questions:
            return self._template_questions(topic, count)
        return questions[:count]

    async def _gather(
        self,
        questions: Sequence[str],
        top_k: int,
        source_ids: Sequence[str] | None,
        tenant_id: str,
        retrieval: RetrievalContext | None = None,
        on_progress: ProgressCallback | None = None,
    ) -> tuple[list[Citation], int, bool]:
        citations: list[Citation] = []
        seen: set[str] = set()
        web_used = 0
        web_search = self.web_search
        web_available = bool(web_search is not None and web_search.healthcheck())
        total = max(1, len(questions))
        for position, question in enumerate(questions, start=1):
            if retrieval is not None:
                found, _ = await retrieval.search(
                    self.vectorstore,
                    question,
                    top_k=top_k,
                    source_ids=source_ids,
                    tenant_id=tenant_id,
                    min_score=self.min_score,
                )
            else:
                found = await self.vectorstore.search(
                    question,
                    top_k=top_k,
                    source_ids=source_ids,
                    tenant_id=tenant_id,
                    min_score=self.min_score,
                )
            for citation in found:
                key = f"kb:{citation.source_id}:{citation.chunk_index}"
                if key in seen:
                    continue
                seen.add(key)
                citations.append(citation)
            if web_available and web_search is not None:
                results = await web_search.search(question, limit=self.web_limit)
                web_used += len(results)
                for index, result in enumerate(results):
                    key = f"web:{result.url}"
                    if key in seen:
                        continue
                    seen.add(key)
                    citations.append(
                        Citation(
                            source_id=result.url or f"web-{index}",
                            source_name=result.title or result.url,
                            chunk_id=f"web-{index}",
                            chunk_index=index,
                            text=result.snippet,
                            snippet=result.snippet,
                            score=0.0,
                            start=0,
                            end=0,
                            sources=list(result.sources),
                            meta={
                                "kind": "web",
                                "url": result.url,
                                "sources": list(result.sources),
                            },
                        )
                    )
            if on_progress is not None:
                on_progress("retrieving", 0.10 + 0.45 * position / total)
        if self.max_evidence > 0:
            citations = citations[: self.max_evidence]
        return citations, web_used, web_available

    async def _apply_rerank(
        self,
        query: str,
        citations: list[Citation],
        user_id: str,
        retrieval: RetrievalContext | None = None,
        on_progress: ProgressCallback | None = None,
    ) -> list[Citation]:
        if not citations:
            return citations
        if retrieval is not None:
            if not retrieval.rerank.enabled:
                return citations
            reranker = retrieval.rerank.adapter
            weight = retrieval.weights.rerank
            top_n = retrieval.weights.top_n
            rerank_model = retrieval.rerank.model
        else:
            if self.reranker_factory is None:
                return citations
            reranker = self.reranker_factory(user_id or "")
            weight = self.rerank_weight
            top_n = self.rerank_top_n
            rerank_model = str(getattr(reranker, "model", "") or "") or None
        if on_progress is not None:
            on_progress("reranking", 0.55)
        try:
            scores = await reranker.rerank(
                query, [citation.text for citation in citations], top_n
            )
        except Exception as exc:  # noqa: BLE001
            print(f"[research] rerank failed, skipping rerank: {exc!r}")
            if retrieval is not None and "rerank_failed" not in retrieval.warnings:
                retrieval.warnings.append("rerank_failed")
            if on_progress is not None:
                on_progress("reranking", 0.65)
            return citations
        if on_progress is not None:
            on_progress("reranking", 0.65)
        if len(scores) != len(citations):
            return citations
        for citation, score in zip(citations, scores):
            final_score = (1.0 - weight) * citation.score + weight * float(score)
            citation.rerank_score = round(float(score), 6)
            citation.score = round(float(final_score), 6)
            citation.rerank_model = rerank_model
        citations.sort(key=lambda item: item.score, reverse=True)
        return citations

    async def _synthesize(
        self,
        provider: LLMProvider,
        topic: str,
        questions: Sequence[str],
        citations: Sequence[Citation],
        depth: int,
    ) -> tuple[ResearchBrief, str]:
        if getattr(provider, "is_placeholder", False):
            return self._placeholder_brief(topic, questions, citations), PLACEHOLDER_WARNING
        prompt = self._synthesize_prompt(topic, questions, citations, depth)
        text = await provider.complete(prompt)
        payload = _extract_json(text)
        if payload is None:
            retry_prompt = f"{prompt}\n\nOutput only valid JSON, without any explanations or Markdown code blocks."
            text = await provider.complete(retry_prompt)
            payload = _extract_json(text)
        if payload is None:
            raise ResearchParseError("the model output could not be parsed as structured JSON")
        return _brief_from_payload(payload), ""

    def _warning(
        self,
        provider: LLMProvider,
        citations: Sequence[Citation],
        web_available: bool,
        extra: str,
    ) -> str:
        parts: list[str] = []
        if extra:
            parts.append(extra)
        if getattr(provider, "is_placeholder", False):
            parts.append(PLACEHOLDER_WARNING)
        if not citations:
            parts.append(NO_EVIDENCE_WARNING)
        elif not web_available:
            parts.append(WEB_DISABLED_WARNING)
        return "；".join(dict.fromkeys(parts))

    @staticmethod
    def _template_questions(topic: str, count: int) -> list[str]:
        questions: list[str] = []
        for index in range(count):
            pattern = QUESTION_PATTERNS[index % len(QUESTION_PATTERNS)]
            questions.append(pattern.format(topic=topic))
        return questions

    def _plan_prompt(self, topic: str, count: int) -> str:
        return "\n".join(
            [
                "You are a senior research planner and need to break a research topic into searchable, answerable sub-questions.",
                f"- Research topic: {topic}",
                f"- Number of sub-questions: exactly {count}",
                "- Sub-questions must be complementary and cover definitions, key elements, pitfalls, methods, and evaluation.",
                "Output only a JSON array of strings, for example [\"first sub-question\", \"second sub-question\"], with no explanations.",
            ]
        )

    def _synthesize_prompt(
        self,
        topic: str,
        questions: Sequence[str],
        citations: Sequence[Citation],
        depth: int,
    ) -> str:
        lines = [
            "You are a rigorous researcher. Synthesize a research brief based only on the retrieved evidence provided.",
            "",
            f"## Research topic\n{topic}",
            "",
            "## Sub-questions",
        ]
        lines.extend(f"- {question}" for question in questions)
        lines.extend(
            [
                "",
                "## Evidence",
            ]
        )
        for index, citation in enumerate(citations, start=1):
            snippet = (citation.snippet or citation.text or "")[: self.evidence_char_limit]
            lines.append(f"[E{index}] {citation.source_name}: {snippet}")
        if not citations:
            lines.append("(No evidence retrieved; you must explicitly note the lack of material in gaps)")
        lines.extend(
            [
                "",
                "## Output requirements",
                "Output only a single JSON object, without Markdown code blocks or any explanations; the fields are:",
                '{"summary": "3-6 sentence research overview",',
                ' "findings": [{"title": "Finding title", "detail": "Concrete explanation", "evidence": ["E1"]}],',
                ' "contradictions": [{"claim": "Conflicting conclusion", "evidence": ["E1","E2"]}],',
                ' "gaps": ["Missing material"],',
                ' "next_steps": ["Suggested next step"]}',
                f"- findings must contain {max(3, depth * 2)}-{max(6, depth * 3)} items, each citing an evidence marker.",
                "- Do not introduce facts, data, or conclusions beyond the evidence; when evidence is insufficient, record it in gaps rather than fabricating.",
            ]
        )
        return "\n".join(lines)

    def _placeholder_brief(
        self,
        topic: str,
        questions: Sequence[str],
        citations: Sequence[Citation],
    ) -> ResearchBrief:
        findings: list[ResearchFinding] = []
        for index, citation in enumerate(citations, start=1):
            snippet = (citation.snippet or citation.text or "").strip()
            findings.append(
                ResearchFinding(
                    title=f"Key points from {citation.source_name}",
                    detail=snippet[: self.evidence_char_limit] or "the evidence snippet is empty",
                    evidence=[f"E{index}"],
                )
            )
        if not findings:
            findings.append(
                ResearchFinding(
                    title=f"No usable evidence for {topic} yet",
                    detail="No hits in the knowledge base or web search; more material is needed before synthesis.",
                    evidence=[],
                )
            )
        gaps = list(questions[:3]) if citations else [f"{topic} lacks traceable material"]
        contradictions: list[ResearchContradiction] = []
        if len(citations) >= 3:
            contradictions.append(
                ResearchContradiction(
                    claim="Placeholder synthesis: the evidence items emphasize different aspects; manual confirmation is needed on whether their definitions differ",
                    evidence=["E1", "E3"],
                )
            )
        summary = (
            f"Retrieved {len(citations)} pieces of evidence on \"{topic}\", covering the sub-questions: "
            + "; ".join(questions)
            + ". The conclusions below are organized item by item from the evidence and make no inferences beyond it."
        )
        return ResearchBrief(
            summary=summary,
            findings=findings,
            contradictions=contradictions,
            gaps=gaps,
            next_steps=[
                "Fill the material gaps in the sub-questions and run the research again",
                "Turn the confirmed conclusions into a course blueprint or a long-form draft",
            ],
        )


def _parse_questions(raw: str) -> list[str]:
    text = (raw or "").strip()
    if not text:
        return []
    if text.startswith("```"):
        text = re.sub(r"^```[a-zA-Z]*\s*", "", text)
        text = re.sub(r"\s*```$", "", text).strip()
    start = text.find("[")
    end = text.rfind("]")
    candidate = text[start : end + 1] if start != -1 and end > start else text
    try:
        payload = json.loads(candidate)
    except (TypeError, ValueError):
        return [
            line.strip(" -*\t0123456789.")
            for line in text.splitlines()
            if line.strip(" -*\t0123456789.")
        ][:9]
    if not isinstance(payload, list):
        return []
    questions: list[str] = []
    for item in payload:
        if isinstance(item, str) and item.strip():
            questions.append(item.strip())
        elif isinstance(item, Mapping):
            value = item.get("question") or item.get("title")
            if isinstance(value, str) and value.strip():
                questions.append(value.strip())
    return questions


def _extract_json(raw: str) -> dict[str, Any] | None:
    if not raw:
        return None
    text = raw.strip()
    if text.startswith("```"):
        text = re.sub(r"^```[a-zA-Z]*\s*", "", text)
        text = re.sub(r"\s*```$", "", text).strip()
    start = text.find("{")
    end = text.rfind("}")
    if start == -1:
        return None
    candidate = text[start : end + 1] if end > start else text[start:]
    for attempt in (candidate, _repair_json(candidate)):
        try:
            payload = json.loads(attempt)
        except (TypeError, ValueError):
            continue
        if isinstance(payload, dict):
            return payload
    return None


def _repair_json(text: str) -> str:
    repaired = re.sub(r",\s*([}\]])", r"\1", text)
    repaired = re.sub(r"[\x00-\x1f](?![\n\r\t])", " ", repaired)
    repaired += "]" * max(0, repaired.count("[") - repaired.count("]"))
    repaired += "}" * max(0, repaired.count("{") - repaired.count("}"))
    return repaired


def _as_str(value: Any) -> str:
    return value.strip() if isinstance(value, str) else ""


def _as_str_list(value: Any) -> list[str]:
    if not isinstance(value, list):
        return []
    return [item.strip() for item in value if isinstance(item, str) and item.strip()]


def _brief_from_payload(payload: Mapping[str, Any]) -> ResearchBrief:
    findings: list[ResearchFinding] = []
    raw_findings = payload.get("findings")
    if isinstance(raw_findings, list):
        for item in raw_findings:
            if not isinstance(item, Mapping):
                continue
            title = _as_str(item.get("title"))
            detail = _as_str(item.get("detail"))
            if not title and not detail:
                continue
            findings.append(
                ResearchFinding(
                    title=title or detail[:30],
                    detail=detail,
                    evidence=_as_str_list(item.get("evidence")),
                )
            )
    contradictions: list[ResearchContradiction] = []
    raw_contradictions = payload.get("contradictions")
    if isinstance(raw_contradictions, list):
        for item in raw_contradictions:
            if not isinstance(item, Mapping):
                continue
            claim = _as_str(item.get("claim"))
            if not claim:
                continue
            contradictions.append(
                ResearchContradiction(
                    claim=claim,
                    evidence=_as_str_list(item.get("evidence")),
                )
            )
    return ResearchBrief(
        summary=_as_str(payload.get("summary")),
        findings=findings,
        contradictions=contradictions,
        gaps=_as_str_list(payload.get("gaps")),
        next_steps=_as_str_list(payload.get("next_steps")),
    )
